/* Neural Strata — Phase 8 (B4): the Alerts panel.  Zero dependencies.
   ---------------------------------------------------------------------------
   This is the half of the alerting system an operator actually touches, and the
   whole reason it is a *panel* rather than a toast: a warning nobody can audit is
   a rumour. Every row here answers four questions in one line —

       what happened · how bad · who was told · did it arrive

   and the last one is the point of the phase. `✓local ✓dash ✗SMS` is not
   decoration: it is the delivery ledger (`alert_deliveries`) rendered, and it is
   what makes "a warning nobody received is not a warning" checkable at a glance
   instead of assertable in a report.

   Four deliberate rules:

   1. **A suppression is never invisible.** An ADVISORY alert shows as a grey row
      that says *"ADVISORY — no SMS by policy"*, in the server's own words (read
      from `/api/alerts/policy`). A quiet system that does not say why it was
      quiet is indistinguishable from a broken one.
   2. **Acknowledging is a human act with a name (SRS §5.5).** The operator is
      chosen from a list and remembered; the server refuses a blank one, and this
      panel never sends one.
   3. **Never blank on a failed poll.** The last good frame stays on screen with
      its age, exactly like the GIS card: an empty alert list during an outage is
      the most dangerous thing this panel could show.
   4. **The colour codes are the ones the hardware uses.** A row's chip uses the
      same red/amber as the strips (`src/common/leds.h`) so a person reading the
      console and a person standing at the junction are looking at the same signal.

   Mounted from `index.html` as `<div id="alerts-panel">`; this file finds it and
   starts the polls on its own, per the §2 tree (the built page is generated by
   `tools/build-single.js`, and check.js forbids inline script blocks).
*/
(function () {
  "use strict";

  const TIER = {
    CRITICAL: { fg: "#ff6b6b", bg: "rgba(214,69,69,.18)", label: "CRITICAL" },
    HIGH:     { fg: "#ffb84d", bg: "rgba(224,165,32,.18)", label: "HIGH" },
    ELEVATED: { fg: "#ffe08a", bg: "rgba(224,165,32,.10)", label: "ELEVATED" },
    WATCH:    { fg: "#9fb3c8", bg: "rgba(159,179,200,.10)", label: "WATCH" },
    ADVISORY: { fg: "#8d99a8", bg: "rgba(141,153,168,.12)", label: "ADVISORY" }
  };
  const STATE_COLOUR = { NEW: "#ffb84d", ACTIVE: "#ff6b6b", ACKED: "#4ade80", CLOSED: "#8d99a8" };
  const CHANNEL_SHORT = { local: "local", dashboard: "dash", sms: "SMS", email: "email", lifecycle: "log" };

  const OP_KEY = "ns.alert.operator";          /* localStorage — the shift's name */
  let policy = null;                            /* /api/alerts/policy, once      */
  let lastGood = null;                          /* last frame that parsed        */
  let filter = null;                            /* a tier chip, or null = all    */
  let busy = {};                                /* ids mid-ACK, so a double tap  */

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function ago(seconds) {
    const s = Math.max(0, Math.round(seconds || 0));
    if (s < 60) return s + "s";
    if (s < 3600) return Math.floor(s / 60) + "m " + (s % 60) + "s";
    return Math.floor(s / 3600) + "h " + Math.floor((s % 3600) / 60) + "m";
  }

  function operator() {
    try { return localStorage.getItem(OP_KEY) || "Safety Officer"; }
    catch (e) { return "Safety Officer"; }
  }

  function setOperator(name) {
    try { localStorage.setItem(OP_KEY, name); } catch (e) { /* private mode */ }
  }

  /* ── the ledger column ──────────────────────────────────────────────────── *
     ✓ = delivered, ✗ = failed-but-queued, · = not a channel for this tier.
     The middle one matters: `✗` on a queued SMS is "not yet", and calling that a
     failure would make an offline site look like a broken one.               */
  function ledger(a) {
    if (a.suppressed) {
      return `<span class="lg n" title="${esc(a.suppress_reason || "suppressed by policy")}">`
           + `— no message out —</span>`;
    }
    const mark = (ok, ch) =>
      `<span class="lg ${ok ? "y" : "n"}" title="${ch}: ${ok ? "delivered" : "not delivered"}">`
      + `${ok ? "✓" : "✗"}${esc(CHANNEL_SHORT[ch])}</span>`;
    return mark(a.local_dispatched, "local") + mark(a.dash_dispatched, "dashboard")
         + mark(a.sms_dispatched, "sms") + mark(a.email_dispatched, "email");
  }

  /* A row can come from two places — the live machine (which publishes `age_s`)
     or `alerts_history` (which publishes `ts`). The panel computes the age from
     whichever it was given, so a stored alert does not read "0s ago" forever. */
  function ageOf(a) {
    if (a.age_s != null) return a.age_s;
    if (a.ts) return (Date.now() - Date.parse(a.ts)) / 1000;
    return 0;
  }

  function row(a) {
    const t = TIER[a.severity] || TIER.WATCH;
    const closed = a.state === "CLOSED";
    const advisory = a.suppressed || a.severity === "ADVISORY";
    const dim = closed || advisory;
    const ackable = !closed && a.state !== "ACKED" && a.id != null;

    return `<div class="r" data-id="${a.id == null ? "" : a.id}" `
      + `style="display:flex;gap:10px;align-items:flex-start;padding:8px 10px;border-left:3px solid ${dim ? "#8d99a8" : t.fg};`
      + `background:${dim ? "rgba(141,153,168,.06)" : t.bg};border-radius:4px;margin:6px 0;`
      + `font:12px/1.45 Carlito,Calibri,sans-serif;color:${dim ? "#6d7783" : "#e8eef7"}">`
      + `<span style="flex:0 0 78px;font-weight:bold;letter-spacing:.4px;color:${dim ? "#8d99a8" : t.fg}">`
      + `${esc(t.label)}</span>`
      + `<span style="flex:1">`
      + `<span style="opacity:.85">${esc(a.reference || "—")}</span> · `
      + `<b>${esc((a.node_label || a.node_id || "site"))}</b> · `
      + `${esc(a.event_type)} · <span style="opacity:.8">${ago(ageOf(a))} ago</span>`
      + (a.ttf_seconds != null
          ? ` · TTF <b>${esc(a.ttf_seconds)}s</b>`
            + (a.ttf_q10 != null ? ` (${esc(a.ttf_q10)}–${esc(a.ttf_q90)})` : "")
          : "")
      + (a.progression_stage && a.progression_stage !== "STABLE"
          ? ` · <span style="color:${dim ? "#8d99a8" : "#ffd7a1"}">${esc(a.progression_stage)}</span>` : "")
      + `<br><span style="opacity:.92">${esc((a.recommended_action || a.text || "").slice(0, 150))}</span>`
      + (advisory && a.suppress_reason
          ? `<br><span style="color:#8d99a8;font-style:italic">${esc(a.suppress_reason)}</span>` : "")
      + (a.last_error
          ? `<br><span style="color:#c98b8b;opacity:.9">${esc(a.last_error.slice(0, 120))}</span>` : "")
      + `<br><span style="margin-top:3px;display:inline-block">${ledger(a)}</span>`
      + `</span>`
      + `<span style="flex:0 0 116px;text-align:right">`
      + `<span style="color:${STATE_COLOUR[a.state] || "#9fb3c8"};font-weight:bold">${esc(a.state)}</span>`
      + (a.acked_by ? `<br><span style="opacity:.75">${esc(a.acked_by)}</span>` : "")
      + (ackable
          ? `<br><button type="button" class="ackbtn" data-ack="${esc(a.id)}" `
            + `style="margin-top:4px;cursor:pointer;background:#1b3a5c;color:#dfe7f3;border:1px solid #2c5b8a;`
            + `border-radius:3px;padding:2px 10px;font:11px Carlito,Calibri,sans-serif">`
            + `${busy[a.id] ? "…" : "ACK"}</button>`
          : "")
      + `</span></div>`;
  }

  function tierChips(d) {
    const counts = {};
    (d.alerts || []).forEach(a => { counts[a.severity] = (counts[a.severity] || 0) + 1; });
    const order = ["CRITICAL", "HIGH", "ELEVATED", "WATCH", "ADVISORY"];
    let s = `<span style="display:inline-flex;gap:6px;align-items:center;flex-wrap:wrap">`;
    s += `<button type="button" class="chip${filter ? "" : " on"}" data-chip="" style="cursor:pointer">`
       + `ALL <b>${d.count || 0}</b></button>`;
    order.forEach(tier => {
      const n = counts[tier] || 0;
      if (!n) return;
      const t = TIER[tier];
      s += `<button type="button" class="chip${filter === tier ? " on" : ""}" data-chip="${tier}" `
         + `style="cursor:pointer;color:${t.fg}">${t.label} <b>${n}</b></button>`;
    });
    s += `</span>`;
    return s;
  }

  /* ── the lamps ────────────────────────────────────────────────────────────
     The Alerts panel is about *messages*: who was told, and did it land. This
     strip of it is about the thing a person standing in the tunnel actually
     sees — the junction indication. Every `#CMD` frame the server writes is
     recorded at the one door it leaves through (`routing.push_hub_command`), and
     that record is served on this same 2 s poll, so "the siren is sounding" and
     "the cable is out" are distinguishable here rather than at the hub.

     An empty inbox with a hub attached is a fact, not a blank: it means the
     server has not pushed a plan yet. A filled inbox with every dot hollow means
     the plan is being written into a cable nobody is reading. */
  function lamps(dl) {
    if (!dl) return "";
    const inbox = dl.junction_inbox || [];
    const dot = (e) => e.delivered
      ? '<span style="color:#4ade80">&#9679;</span>'
      : '<span style="color:#ff8a8a">&#9675;</span>';
    const one = (e) => `<span class="lg" title="${esc(e.detail || "")}">`
      + `${dot(e)} <b style="color:#cfd9e4">${esc(e.key)}</b> ${esc(e.pattern || e.cmd)}`
      + `</span>`;
    const lamps_s = inbox.length
      ? inbox.map(one).join("")
      : '<span class="lg" style="color:#8d99a8">no commands written yet</span>';
    const right = dl.attached
      ? `${dl.changes || 0} change(s) · ${dl.reasserts || 0} pulse(s) · `
        + `re-assert every ${Math.round(dl.reassert_s || 0)}s · a silent hub falls `
        + `back to amber after ${Math.round(dl.silence_s || 0)}s`
      : "no hub attached — the strips are not being driven (SIM)";
    return `<div style="margin:6px 0;padding:6px 8px;background:#0b1a2e;border:1px solid #1d3554;`
         + `border-radius:3px;display:flex;justify-content:space-between;gap:10px;flex-wrap:wrap">`
         + `<div style="display:flex;gap:10px;flex-wrap:wrap;align-items:center">`
         + `<span style="font:11px Carlito,Calibri,sans-serif;color:#8d99a8;letter-spacing:.06em">`
         + `JUNCTION LAMPS</span>${lamps_s}</div>`
         + `<span style="font:11px Carlito,Calibri,sans-serif;color:#8d99a8">${esc(right)}</span>`
         + `</div>`;
  }

  function render(host, d) {
    const alerts = (d.alerts || []).filter(a => !filter || a.severity === filter);
    const open = d.open || 0;
    const escal = policy ? `escalate ${Math.round(policy.escalate_s)}s · dedup ${Math.round(policy.dedup_s)}s` : "";
    const sms = policy && policy.sms
      ? (policy.sms.configured ? `SMS ≤${policy.sms.max_per_hour}/h` : "SMS not configured (queued)")
      : "";

    let s = `<style>
      #alerts-panel .chip { background:#10233f;border:1px solid #2c5b8a;border-radius:3px;
        color:#b9c6d6;font:11px Carlito,Calibri,sans-serif;padding:2px 8px }
      #alerts-panel .chip.on { background:#1b3a5c;border-color:#4a8ac0;color:#f0f6ff }
      #alerts-panel .lg { display:inline-block;margin-right:8px;font:11px Carlito,Calibri,sans-serif }
      #alerts-panel .lg.y { color:#4ade80 } #alerts-panel .lg.n { color:#ff8a8a }
      #alerts-panel .ackbtn:hover { background:#24507c }
      #alerts-panel .r:hover { outline:1px solid #2c5b8a }
    </style>`;
    s += `<div style="display:flex;justify-content:space-between;align-items:center;gap:10px;flex-wrap:wrap">`;
    s += `<div style="font:12px Carlito,Calibri,sans-serif;color:#b9c6d6">`
       + `<b style="color:${open ? "#ff6b6b" : "#4ade80"}">${open} open</b> · `
       + `keeping ${d.count || 0} of the last ${(d.alerts || []).length} · ${esc(escal)}`
       + (sms ? ` · ${esc(sms)}` : "") + `</div>`;
    s += `<div style="display:flex;gap:8px;align-items:center">`
       + `<span id="al-ops" style="display:flex;align-items:center;gap:4px"></span>`
       + `<span style="font:11px Carlito,Calibri,sans-serif;color:#8d99a8" id="al-age"></span>`
       + `</div></div>`;
    s += `<div style="margin:8px 0" id="al-chips">${tierChips(d)}</div>`;
    s += lamps(d.downlink);
    s += `<div id="al-list" style="max-height:340px;overflow:auto">`
       + (alerts.length ? alerts.map(row).join("")
          : `<div style="font:12px Carlito,Calibri,sans-serif;color:#8d99a8;padding:10px">`
            + `No alerts on record. Nothing suppressed, nothing dropped — the log is simply empty.</div>`)
       + `</div>`;
    s += `<div style="margin-top:8px;font:11px Carlito,Calibri,sans-serif;color:#8d99a8">`
       + `Ledger: ✓ delivered · ✗ not delivered (queued for retry) · a grey row was `
       + `suppressed by policy and says so. CRITICAL is never auto-suppressed (SRS §5.5).</div>`;

    host.innerHTML = s;
    paintOperator(host);
    paintAge(host, d);
    bind(host);
  }

  function paintOperator(host) {
    const box = host.querySelector("#al-ops");
    if (!box) return;
    const list = (policy && policy.operators) || ["Safety Officer", "Control Room", "Test"];
    box.innerHTML = `<span style="font:11px Carlito,Calibri,sans-serif;color:#8d99a8">ACK as</span>`
      + `<select id="al-op" style="background:#10233f;color:#dfe7f3;border:1px solid #2c5b8a;`
      + `border-radius:3px;font:11px Carlito,Calibri,sans-serif;padding:2px 4px">`
      + list.map(n => `<option${n === operator() ? " selected" : ""}>${esc(n)}</option>`).join("")
      + `</select>`;
    const sel = box.querySelector("#al-op");
    if (sel) sel.addEventListener("change", () => setOperator(sel.value));
  }

  function paintAge(host, d) {
    const el = host.querySelector("#al-age");
    if (!el) return;
    el.textContent = d.poll_failed
      ? `poll failed — showing the last good frame (${ago(d.stale_s)})`
      : `updated ${new Date().toLocaleTimeString()}`;
    if (d.poll_failed) el.style.color = "#ffb84d"; else el.style.color = "#8d99a8";
  }

  function bind(host) {
    host.querySelectorAll("[data-chip]").forEach(btn => {
      btn.addEventListener("click", () => {
        filter = btn.getAttribute("data-chip") || null;
        if (lastGood) render(host, lastGood);
      });
    });
    host.querySelectorAll("[data-ack]").forEach(btn => {
      btn.addEventListener("click", async () => {
        const id = btn.getAttribute("data-ack");
        busy[id] = true;
        try {
          const r = await fetch(window.apiUrl(`/api/alerts/${id}/ack`), {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ operator: operator() })
          });
          const j = await r.json();
          if (!j.ok) { btn.textContent = "refused"; btn.title = j.error || "refused"; }
        } catch (e) {
          btn.textContent = "offline";
        } finally {
          busy[id] = false;
          await tick();                       /* re-read the truth, do not guess */
        }
      });
    });
  }

  async function tick() {
    const host = document.getElementById("alerts-panel");
    if (!host) return;
    try {
      if (!policy) {
        const p = await fetch(window.apiUrl("/api/alerts/policy"));
        if (p.ok) policy = await p.json();
      }
      const r = await fetch(window.apiUrl("/api/alerts?limit=50"));
      const d = await r.json();
      d.poll_failed = false;
      lastGood = d;
      lastGood.at = Date.now();
      render(host, d);
    } catch (e) {
      /* Rule 3: a failed poll never blanks the panel. */
      if (lastGood) {
        lastGood.poll_failed = true;
        lastGood.stale_s = (Date.now() - (lastGood.at || Date.now())) / 1000;
        render(host, lastGood);
      } else {
        host.innerHTML = `<div style="font:12px Carlito,Calibri,sans-serif;color:#ffb84d;padding:10px">`
          + `Waiting for /api/alerts… (the panel keeps its last good frame rather than blanking).</div>`;
      }
    }
  }

  function mount() {
    const host = document.getElementById("alerts-panel");
    if (!host || host.dataset.alMounted) return;      /* never poll twice */
    host.dataset.alMounted = "1";
    host.style.cssText += ";font:12px Carlito,Calibri,sans-serif";
    tick();
    setInterval(tick, 2000);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", mount);
  } else {
    mount();
  }
})();

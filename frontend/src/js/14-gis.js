/* Neural Strata — Phase 7 (B5): the GIS plan card.  (was frontend/gis-map.js)
   Zero dependencies, 100% offline, SVG-based.
   Positions are constants; RISK COLOURS are live from the AI (/api/map, 2 s poll),
   and from Phase 7 the escape ROUTES are live too — one polyline per level, drawn
   from `routes.per_level[level].path`, with a HOLD banner when the router cannot
   find anyone a way out.

   Where it lives, and why it moved
   -------------------------------
   The tree (§2) lists this panel as `frontend/gis-map.js`, a root-level file — the
   layout from before the frontend gained a build step. In the delivered layout the
   single shipped page is `frontend/index.html`, generated by
   `tools/build-single.js` from `frontend/src/`, and every script it contains is a
   numbered file under `frontend/src/js/`. So the panel is
   `frontend/src/js/14-gis.js`, and the root copy is **not** created: a second copy
   of the panel outside the bundle is an edit that never ships. This is the same
   reconciliation Rev 6.0.6 recorded for the black-box panel.

   The backend still serves the frontend directory as static assets
   (`/assets/<path>` and the catch-all `/<path>`), and `/assets/gis-map.js` will
   404 — there is no such file any more, and the page does not ask for one.

   The card is mounted from `index.html` as `<div id="gis-map">`; this file finds it
   and starts the 2 s poll on its own.
*/
(function () {
  "use strict";
  const RISK_COLOR = { NOMINAL: "#2e9e5b", WARNING: "#e0a520", CRITICAL: "#d64545" };
  const RISK_FILL  = { NOMINAL: "rgba(46,158,91,.16)", WARNING: "rgba(224,165,32,.20)", CRITICAL: "rgba(214,69,69,.24)" };
  const W = 700, H = 380, P = 52;

  function esc(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function project(d) {
    const pts = d.nodes.concat(d.junctions, d.exits);
    let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
    pts.forEach(p => {
      x0 = Math.min(x0, p.lon); x1 = Math.max(x1, p.lon);
      y0 = Math.min(y0, p.lat); y1 = Math.max(y1, p.lat);
    });
    const sx = x => (x - x0) / ((x1 - x0) || 1) * (W - 2 * P) + P;
    const sy = y => H - ((y - y0) / ((y1 - y0) || 1) * (H - 2 * P) + P);
    return { sx, sy };
  }

  function render(host, d) {
    const { sx, sy } = project(d);
    const byId = {};
    d.nodes.concat(d.junctions, d.exits).forEach(p => { byId[p.id] = p; });

    let s = "";
    s += `<svg viewBox="0 0 ${W} ${H}" width="100%" height="100%" xmlns="http://www.w3.org/2000/svg" font-family="Carlito,Calibri,sans-serif">`;
    s += `<style>
      .gis-pulse { animation: gisp 1.1s ease-in-out infinite; }
      @keyframes gisp { 0%,100% { opacity:1 } 50% { opacity:.25 } }
      .gis-lab { font-size:11px; fill:#39414d } .gis-zlab { font-size:10px; font-weight:bold }
    </style>`;

    // header chip
    const sysC = RISK_COLOR[d.system_status] || RISK_COLOR.NOMINAL;
    s += `<rect x="10" y="10" width="${W - 20}" height="26" rx="5" fill="#10233f"/>`;
    s += `<text x="20" y="27" font-size="12" fill="#fff" font-weight="bold">GIS · ${esc(d.site.name)} — fixed baseline, no GPS module</text>`;
    s += `<circle cx="${W - 108}" cy="23" r="5" fill="${sysC}"/>`;
    s += `<text x="${W - 98}" y="27" font-size="11" fill="#dfe7f3">${esc(d.system_status)}</text>`;

    // Four zones, drawn with a gap so neighbouring nodes do not look like one
    // area. Each zone already belongs to one node; the colour follows that node.
    function pulled(points) {
      const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
      const cx = xs.reduce((a, b) => a + b, 0) / points.length;
      const cy = ys.reduce((a, b) => a + b, 0) / points.length;
      return points.map(p => [(p[0] + cx) / 2, (p[1] + cy) / 2]);
    }
    d.zones.forEach(z => {
      const raw = z.polygon.map(pl => [sx(pl[1]), sy(pl[0])]);
      const pts = pulled(raw).map(p => `${p[0]},${p[1]}`).join(" ");
      const owner = (d.nodes || []).find(n => z.nodes && z.nodes[0] === n.id);
      const risk = (owner && owner.status) || "NOMINAL";
      const alarmed = risk === "WARNING" || risk === "CRITICAL";
      s += `<polygon points="${pts}" fill="${RISK_FILL[risk] || RISK_FILL.NOMINAL}" stroke="${RISK_COLOR[risk] || RISK_COLOR.NOMINAL}" stroke-width="${alarmed ? 2.4 : 1.4}"${alarmed ? ' class="gis-pulse"' : ""}/>`;
      const labelAt = pulled(raw)[0];
      const who = (z.nodes && z.nodes[0]) ? z.nodes[0].replace("node_", "N") : z.id;
      s += `<text class="gis-zlab" x="${labelAt[0] + 8}" y="${labelAt[1] + 16}" fill="${RISK_COLOR[risk] || RISK_COLOR.NOMINAL}">${esc(who)} · ${esc(z.name)} · ${esc(risk)}</text>`;
    });

    // links — Phase 7: objects (`from`/`to`/`state`/`cost`/`hazard`), per §A.3.6.
    // Before Phase 7 this file indexed them as arrays (`L[0]`, `L[1]`), which is
    // what the old server sent; the contract of record always said objects.
    d.links.forEach(L => {
      const a = byId[L.from], b = byId[L.to];
      if (!a || !b) return;
      const blocked = L.state === "BLOCKED";
      // A hazardous leg is drawn thicker. The width is the *hazard*, not the
      // cost: a blocked leg is infinite, and an infinite-width line is not a map.
      const w = blocked ? 2.2 : 1.4 + Math.min(3.0, (L.hazard || 0) * 0.35);
      s += `<line x1="${sx(a.lon)}" y1="${sy(a.lat)}" x2="${sx(b.lon)}" y2="${sy(b.lat)}" ` +
           `stroke="${blocked ? "#d64545" : "#8a97ab"}" stroke-width="${w.toFixed(1)}" ` +
           `${blocked ? 'stroke-dasharray="7 4"' : 'stroke-dasharray="4 3"'}>` +
           `<title>${esc(L.from)} → ${esc(L.to)} · ${esc(L.state)}` +
           `${L.cost == null ? " (blocked)" : " · " + L.cost.toFixed(1) + " m risk-weighted"}` +
           `${L.base_m ? " (" + L.base_m.toFixed(1) + " m actual)" : ""}</title></line>`;
    });

    // computed escape routes — the whole point of the card (Phase 7).
    const ROUTE_COLOUR = { 1: "#1f9d55", 2: "#2f6fd0" };
    const routes = (d.routes && d.routes.per_level) || {};
    Object.keys(routes).forEach(lv => {
      const r = routes[lv];
      if (!r || r.state !== "OPEN" || !r.path || r.path.length < 2) return;
      const pts = r.path.map(id => byId[id]).filter(Boolean);
      if (pts.length < 2) return;
      const col = ROUTE_COLOUR[lv] || "#1f9d55";
      s += `<polyline points="${pts.map(p => `${sx(p.lon)},${sy(p.lat)}`).join(" ")}" ` +
           `fill="none" stroke="${col}" stroke-width="3.4" stroke-linecap="round" ` +
           `stroke-linejoin="round" opacity="0.9">` +
           `<title>Level ${esc(lv)} escape route → ${esc(r.exit)} · ${r.base_m} m · ~` +
           `${r.eta_s}s at ${(d.routes.walk_speed_mps || 1.2)} m/s</title></polyline>`;
      const end = pts[pts.length - 1];
      s += `<circle cx="${sx(end.lon)}" cy="${sy(end.lat)}" r="4.6" fill="${col}" stroke="#fff" stroke-width="1.4"/>`;
    });

    // exits
    d.exits.forEach(e => {
      const x = sx(e.lon), y = sy(e.lat);
      s += `<rect x="${x - 7}" y="${y - 7}" width="14" height="14" rx="3" fill="#10233f" stroke="#fff" stroke-width="1.5" transform="rotate(45 ${x} ${y})"/>`;
      s += `<text class="gis-lab" x="${x}" y="${y + 22}" text-anchor="middle" font-weight="bold">${esc(e.label || e.id)}</text>`;
    });

    // junctions (passive 8-LED strips)
    d.junctions.forEach(j => {
      const x = sx(j.lon), y = sy(j.lat);
      s += `<rect x="${x - 6}" y="${y - 6}" width="12" height="12" fill="#4a5a75" stroke="#fff" stroke-width="1.2"/>`;
      s += `<text class="gis-lab" x="${x}" y="${y - 10}" text-anchor="middle">${j.id}</text>`;
    });

    // nodes
    d.nodes.forEach(n => {
      const x = sx(n.lon), y = sy(n.lat);
      const c = RISK_COLOR[n.status] || RISK_COLOR.NOMINAL;
      const dim = n.active === false ? 0.45 : 1;
      s += `<g opacity="${dim}">`;
      if (n.status === "CRITICAL")
        s += `<circle class="gis-pulse" cx="${x}" cy="${y}" r="16" fill="none" stroke="${c}" stroke-width="2"/>`;
      s += `<circle cx="${x}" cy="${y}" r="9" fill="${c}" stroke="#fff" stroke-width="2">`;
      s += `<title>${esc(n.label)} · ${n.lat.toFixed(5)}°N ${n.lon.toFixed(5)}°E · ${esc(n.status)}${n.active === false ? " · (offline — not yet wired)" : ""}</title></circle>`;
      s += `<text class="gis-lab" x="${x}" y="${y + 22}" text-anchor="middle" font-weight="bold">${esc(n.id.replace("node_", "N"))}</text>`;
      s += `</g>`;
    });

    // Phase 7 footer — the router's verdict, in words, above the legend
    const lv1 = routes["1"], lv2 = routes["2"];
    const bits = [];
    if (lv1 && lv1.exit) bits.push(`L1 → ${lv1.exit} · ${lv1.base_m} m · ~${lv1.eta_s}s`);
    if (lv2 && lv2.exit) bits.push(`L2 → ${lv2.exit} · ${lv2.base_m} m · ~${lv2.eta_s}s`);
    const SITE_HOLD = !!d.hold;
    s += `<g transform="translate(14,${H - 34})" font-size="11" ` +
         `font-family="Carlito,Calibri,sans-serif">`;
    if (SITE_HOLD) {
      s += `<rect x="0" y="-13" width="${W - 28}" height="19" rx="4" fill="#fbe9e9" stroke="#d64545"/>`;
      s += `<text x="8" y="1" fill="#8f2020" font-weight="bold">⚠ EVACUATION HOLD — no safe path from ' +
           'at least one junction. Junctions show an amber hold; crews stay in place.</text>`;
    } else {
      s += `<text x="0" y="0" fill="#2b3a4d">${esc(bits.join("   ·   ") || "computing routes…")}</text>`;
      s += `<text x="${W - 28}" y="0" text-anchor="end" fill="#5b6472">risk-weighted Dijkstra · ` +
           `thicker = more hazardous</text>`;
    }
    s += `</g>`;

    // legend
    s += `<g transform="translate(14,${H - 16})" font-size="10" fill="#5b6472">`;
    s += `<circle cx="6" cy="-3" r="5" fill="#2e9e5b"/><text x="16" y="0">node NOMINAL</text>`;
    s += `<circle cx="92" cy="-3" r="5" fill="#e0a520"/><text x="102" y="0">WARNING</text>`;
    s += `<circle cx="166" cy="-3" r="5" fill="#d64545"/><text x="176" y="0">CRITICAL</text>`;
    s += `<rect x="238" y="-9" width="11" height="11" fill="#4a5a75"/><text x="254" y="0">junction</text>`;
    s += `<rect x="318" y="-9" width="11" height="11" transform="rotate(45 323.5 -3.5)" fill="#10233f"/><text x="334" y="0">exit</text>`;
    s += `<line x1="392" y1="-4" x2="412" y2="-4" stroke="#1f9d55" stroke-width="3.4"/><text x="418" y="0">L1 route</text>`;
    s += `<line x1="470" y1="-4" x2="490" y2="-4" stroke="#2f6fd0" stroke-width="3.4"/><text x="496" y="0">L2 route</text>`;
    s += `<text x="${W - 14}" y="0" text-anchor="end">risk colours = live AI · routes = live Dijkstra</text>`;
    s += `</g></svg>`;
    host.innerHTML = s;
  }

  window.initGisMap = function (containerId) {
    const host = document.getElementById(containerId);
    if (!host) return;
    if (host.dataset.gisMounted) return;          // never mount the poll twice
    host.dataset.gisMounted = "1";
    host.style.cssText = "background:#f7f9fc;border:1px solid #d9e0ea;border-radius:8px;overflow:hidden;";
    let lastGood = null;
    const tick = async () => {
      try {
        const r = await fetch(window.apiUrl("/api/map"));
        if (!r.ok) throw new Error("HTTP " + r.status);
        lastGood = await r.json();
        render(host, lastGood);
      } catch (e) {
        if (lastGood) return; // keep last good frame, never blank the map
        host.innerHTML = '<div style="padding:14px;color:#a03d00;font-family:Calibri,sans-serif;font-size:12px">GIS card: /api/map unreachable — backend offline?</div>';
      }
    };
    tick();
    setInterval(tick, 2000);
  };
})();

// Self-mount. The card is in the evac view of a single-page deck, so it exists in
// the DOM from the first parse and this runs at the end of the body — no
// DOMContentLoaded dance, and no inline <script> in index.html (which
// tools/check.js forbids, and which would break the built file's CSP posture).
if (typeof document !== "undefined" && document.getElementById) {
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () { window.initGisMap("gis-map"); });
  } else {
    window.initGisMap("gis-map");
  }
}

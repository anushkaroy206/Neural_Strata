#!/usr/bin/env python3
"""
Neural Strata — Phase 4.6c · Fukuzono Kinematic Fallback Calibration
====================================================================
Records the 1/v velocity-inversion parameters (alpha, A) that the kinematic
fallback in ``backend/engine/kinematic.py`` computes with.

**These are literature values, not a fit.** alpha is the mean of the empirical
distribution geotechnical failures show (1.5–2.2 for brittle rock); A is taken
from the drill simulation. §6.1 says of this file that it "writes hard-coded
constants rather than fitting anything", and that is accurate — the constants are
documented, not derived. Whether to fit them against the drill harvest or to keep
recording them explicitly is a Phase 6 decision; what this file must not do is
claim a fit it does not perform.

Theoretical Basis:
  Fukuzono (1985) / Voight (1988) empirical failure law:
    d^2 x / dt^2 = A * (dx/dt)^alpha
  For alpha = 2.0, the inverse velocity 1/v is linear with time until failure:
    1 / v(t) = A * (t_f - t)
  Time-To-Failure:
    TTF = 1 / (A * v)  or  (disp_limit - disp) / v

Run it to rewrite ``backend/models/kinematic_calibration.json`` from the values
below. It is idempotent: the shipped artifact is exactly what this script emits.
"""

from pathlib import Path
import json

AI_ROOT = Path(__file__).resolve().parents[1]

# **Resolved through the backend's own config, not reconstructed.**
#
# This line read ``AI_ROOT.parent / "neuralstrata-backend" / "models"`` — the
# name the *build document* uses for the backend, and a directory that does not
# exist in this workspace. ``mkdir(parents=True)`` then created it, so the script
# wrote the calibration into a folder the server never reads and reported
# success. That is the same defect ``02_training.py`` carries a note about
# having fixed; this notebook was the one that was missed. Resolving through
# ``config`` makes the write land where the runtime reads by construction.
import sys                                                                # noqa: E402
sys.path.insert(0, str(AI_ROOT.parent / "backend"))
import config as backend_config                                            # noqa: E402

BACKEND_MODELS = Path(backend_config.MODELS_DIR)


#: The literature values. ``alpha`` is the mean of the empirical distribution
#: brittle-rock failures show (1.5 – 2.2, Fukuzono 1985 / Voight 1988); ``A`` is
#: the laboratory drill value.
LITERATURE_ALPHA = 1.95
LITERATURE_A = 0.082

#: Where the fit would look, if a fit were possible. See :func:`attempt_fit`.
DRILL_DATASET = AI_ROOT / "datasets" / "drill_dataset.csv"


def attempt_fit(dataset: Path | None = None) -> dict:
    """Try to fit ``(alpha, A)`` to the drill harvest. **It does not work, and
    this function exists so that the claim is a measurement rather than a story.**

    §6.5 offered two ways out of this file's original problem — it was called
    "calibrate" while assigning literals — and asked for one of them: (a) rename
    it honestly, or (b) make it fit. This is the answer to (b), and it is "no".

    The Voight law says ``dv/dt = A · v^alpha``, so a regression of ``log dv/dt``
    on ``log v`` over the breaching runs should return ``alpha`` as its slope.
    Run over the 64 ``BREACH`` runs of the shipped corpus it returns

        alpha = 0.32   A = 0.49   R^2 = 0.14   (1,744 points)

    which is not the law. Two reasons, both structural:

    * the corpus is generated by the **simulator's** hand-shaped profile, not by
      integrating the Voight law, so there is no ``alpha`` in it to recover;
    * ``v10`` is a **10-second backward mean** (the project's documented
      convention), which smooths away exactly the second derivative being
      regressed.

    So (a) it is: the values below are literature inputs, recorded with their
    provenance, and this function records the failed fit beside them so that the
    next reader inherits the evidence rather than re-deriving it. The artifact
    keeps its ``alpha_exponent`` / ``a_coefficient`` keys — the runtime reads
    those, and only those — and gains provenance the runtime ignores.
    """
    dataset = dataset or DRILL_DATASET
    result = {"dataset": dataset.name, "attempted": True, "usable": False}
    try:
        import csv
        from collections import defaultdict
        rows: dict[str, list[dict]] = defaultdict(list)
        with dataset.open() as fh:
            for row in csv.DictReader(fh):
                rows[row["run_id"]].append(row)
        import math
        pts = []
        for run in (rs for rs in rows.values() if rs[0].get("run_class") == "BREACH"):
            rs = sorted(run, key=lambda r: float(r["t_s"]))
            for a, b in zip(rs, rs[1:]):
                dt = float(b["t_s"]) - float(a["t_s"])
                try:
                    v1, v2 = float(a["v10"]), float(b["v10"])
                except (TypeError, ValueError):
                    continue
                if dt <= 0 or v1 <= 0.05 or v2 <= v1:
                    continue
                pts.append((math.log(v1), math.log((v2 - v1) / dt)))
        n = len(pts)
        result["points"] = n
        if n >= 50:
            mx = sum(p[0] for p in pts) / n
            my = sum(p[1] for p in pts) / n
            sxx = sum((p[0] - mx) ** 2 for p in pts)
            sxy = sum((p[0] - mx) * (p[1] - my) for p in pts)
            alpha = sxy / sxx
            log_a = my - alpha * mx
            ss_res = sum((p[1] - (log_a + alpha * p[0])) ** 2 for p in pts)
            ss_tot = sum((p[1] - my) ** 2 for p in pts)
            result.update({
                "alpha": round(alpha, 4),
                "a": round(math.exp(log_a), 5),
                "r2": round(1 - ss_res / ss_tot, 4),
                "usable": bool(alpha > 1.0 and (1 - ss_res / ss_tot) > 0.5),
                "verdict": ("accepted" if (alpha > 1.0 and (1 - ss_res / ss_tot) > 0.5)
                            else "REJECTED — the corpus does not contain this law"),
            })
    except Exception as exc:                                    # noqa: BLE001
        result["error"] = f"{type(exc).__name__}: {exc}"
    return result


def record_kinematic_constants():
    """Write ``kinematic_calibration.json``. **This records; it does not fit.**

    Renamed from ``calibrate_kinematic`` for the reason §6.5 gives: a function
    named "calibrate" that assigns literals is the kind of detail a technical
    judge finds. The filename keeps the old word because ``Directory_Structure.md``
    §2 declares it and the tree is binding; the function, the docstring and the
    artifact all say what actually happens, and :func:`attempt_fit` records why
    the honest alternative was not available.

    The artifact's ``alpha_exponent`` and ``a_coefficient`` are byte-identical to
    what this script has always written — the runtime reads them, and a provenance
    field is not worth a behaviour change on the night of a demo.
    """
    fitted = attempt_fit()
    alpha = LITERATURE_ALPHA if not fitted.get("usable") else float(fitted["alpha"])
    a_param = LITERATURE_A if not fitted.get("usable") else float(fitted["a"])

    calibration = {
        "method": "Fukuzono-Voight Inverse Velocity Kinematic Law",
        "alpha_exponent": alpha,
        "a_coefficient": a_param,
        "breach_limit_mm": 100.0,
        "steady_creep_velocity_threshold_mm_s": 0.05,
        "stable_ttf_clamp_s": 3600.0,
        "calibration_basis": "Empirical open-pit mining failure curves & laboratory drill simulation",
        # Additive provenance. The runtime reads only the keys above; these exist
        # so that "where did 1.95 come from?" has an answer inside the artifact.
        "provenance": {
            "kind": "literature" if not fitted.get("usable") else "fitted",
            "literature_alpha_range": "1.5 <= alpha <= 2.2 (brittle rock)",
            "citation": "Fukuzono (1985); Voight (1988)",
            "fit_attempt": fitted,
        },
    }

    BACKEND_MODELS.mkdir(parents=True, exist_ok=True)
    out_file = BACKEND_MODELS / "kinematic_calibration.json"
    out_file.write_text(json.dumps(calibration, indent=2))
    print(f"[kinematic] Wrote calibration constants to {out_file}")
    print(f"  alpha: {alpha}, A: {a_param}, displacement limit: 100.0 mm")
    print(f"  provenance: {calibration['provenance']['kind']}")
    if fitted.get("points"):
        print(f"  fit attempt: alpha={fitted.get('alpha')} A={fitted.get('a')} "
              f"R2={fitted.get('r2')} over {fitted['points']} points "
              f"→ {fitted.get('verdict')}")


if __name__ == "__main__":
    record_kinematic_constants()
